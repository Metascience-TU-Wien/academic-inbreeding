from acib.name_disambiguation.gender import (
    infer_gender_from_full_name,
    infer_gender_from_given_name,
)


def test_gender_detection_covers_common_austrian_names() -> None:
    male = [
        "Alexander",
        "Bernhard",
        "Florian",
        "Johannes",
        "Lukas",
        "Matthias",
        "Stefan",
        "Wolfgang",
    ]
    female = ["Alexandra", "Barbara", "Birgit", "Christina", "Karin", "Lisa", "Martina", "Monika"]
    assert [infer_gender_from_given_name(name).gender for name in male] == ["male"] * len(male)
    assert [infer_gender_from_given_name(name).gender for name in female] == ["female"] * len(
        female
    )


def test_gender_detection_uses_full_name_and_middle_initial() -> None:
    assert infer_gender_from_full_name("weigl, alexander").gender == "male"
    assert infer_gender_from_full_name("muster, barbara").gender == "female"
    assert infer_gender_from_given_name("Gudrun E.").gender == "female"
    assert infer_gender_from_given_name("Manuela").gender == "female"
    assert infer_gender_from_given_name("manula").gender == "female"


