"""Statistical matching suite and result aggregation."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import pandas as pd

from acib.statistical_matching.balance import covariate_balance, effective_sample_size
from acib.statistical_matching.config import StatisticalMatchingConfig
from acib.statistical_matching.data import (
    matching_frame,
    prepare_matching_data,
    propensity_formula,
)
from acib.statistical_matching.outcomes import estimate_outcome
from acib.statistical_matching.strategies import (
    BalancedSample,
    fit_propensity_scores,
    fit_strategy,
)


@dataclass(frozen=True, slots=True)
class StatisticalMatchingResult:
    """All estimates and diagnostic tables generated by the suite."""

    balance_summary: pd.DataFrame
    balanced_samples: dict[str, BalancedSample]
    covariate_balance: pd.DataFrame
    outcome_effects: pd.DataFrame
    adjusted_means: pd.DataFrame
    effect_wide: pd.DataFrame
    se_wide: pd.DataFrame
    diagnostics: pd.DataFrame
    formulas: dict[str, str]
    propensity_scores: pd.DataFrame
    propensity_scores_by_method: pd.DataFrame
    latex_tables: dict[str, str]
    console_table: str
    covariance_type: str
    outcome_types: dict[str, str]
    outcome_aliases: dict[str, str]

    @property
    def effect_table(self) -> pd.DataFrame:
        """Return the wide effect table."""
        return self.effect_wide

    @property
    def standard_error_table(self) -> pd.DataFrame:
        """Return the wide standard-error table."""
        return self.se_wide

    @property
    def absolute_variables(self) -> tuple[str, ...]:
        """Return selected outcomes classified as absolute."""
        return tuple(
            outcome
            for outcome in self.outcome_effects["outcome"].drop_duplicates()
            if outcome in self.outcome_types and self.outcome_types[outcome] == "absolute"
        )

    @property
    def latex_table(self) -> str:
        """Return the family tables joined in relative/absolute order."""
        return "\n\n".join(self.latex_tables.values())


def fit_suite(data: pd.DataFrame, config: StatisticalMatchingConfig) -> StatisticalMatchingResult:
    """Run configured matching methods and estimate configured outcomes.

    :param data: Validated regression input.
    :param config: Matching settings and output contracts.
    :return: Aggregated estimates, samples, tables, and diagnostics.
    """
    prepared = prepare_matching_data(
        data, treatment_variable=config.treatment_variable, exclude_titles=config.exclude_titles
    )
    frame = matching_frame(
        prepared,
        treatment_variable=config.treatment_variable,
        covariates=config.covariates,
        drop_missing=config.drop_missing,
    )
    frame["_matching_row_id"] = range(len(frame))
    effects: list[dict[str, Any]] = []
    means: list[dict[str, Any]] = []
    balances, summaries, diagnostics = [], [], []
    samples: dict[str, BalancedSample] = {}
    for method in config.methods:
        sample = fit_strategy(method, frame, config)
        samples[method] = sample
        balance = covariate_balance(
            frame,
            sample.data,
            sample.weights,
            treatment=config.treatment_variable,
            covariates=config.covariates,
            method=method,
            threshold=config.balance_threshold,
        )
        balances.append(balance)
        treatment = sample.data[config.treatment_variable].astype(bool)
        maximum = float(balance["abs_diff_adjusted"].max())
        summaries.append(
            {
                "method": method,
                "estimand": config.estimand,
                "n_non_inbred": int((~treatment).sum()),
                "n_inbred": int(treatment.sum()),
                "ess_non_inbred": effective_sample_size(sample.weights.loc[~treatment]),
                "ess_inbred": effective_sample_size(sample.weights.loc[treatment]),
                "max_abs_smd": maximum,
                "adequate_balance": maximum < config.balance_threshold,
            }
        )
        diagnostics.append({"method": method, **sample.diagnostics})
        for outcome in config.outcomes:
            effect, adjusted = estimate_outcome(
                sample.data,
                sample.weights,
                outcome=outcome,
                treatment=config.treatment_variable,
                method=method,
                estimand=config.estimand,
                covariance=config.covariance_type,
            )
            effect["estimand"] = config.estimand
            effects.append(effect)
            means.extend(adjusted)
    effect_frame = pd.DataFrame(effects)
    scores = pd.DataFrame(
        {
            config.treatment_variable: frame[config.treatment_variable],
            "propensity_score": fit_propensity_scores(frame, config),
        }
    )
    method_scores = []
    for method, sample in samples.items():
        selected = scores.loc[sample.data["_matching_row_id"]].reset_index(drop=True)
        method_scores.append(
            pd.DataFrame(
                {
                    "method": method,
                    config.treatment_variable: sample.data[config.treatment_variable]
                    .astype(bool)
                    .reset_index(drop=True),
                    "propensity_score": selected["propensity_score"],
                    "weights": sample.weights,
                }
            )
        )
    from acib.statistical_matching.latex import latex_tables
    from acib.statistical_matching.reporting import statistical_matching_console_table

    diagnostic_keys = sorted({key for row in diagnostics for key in row})
    diagnostic_frame = pd.DataFrame(
        [{key: row.get(key) for key in diagnostic_keys} for row in diagnostics]
    )
    return StatisticalMatchingResult(
        pd.DataFrame(summaries),
        samples,
        pd.concat(balances, ignore_index=True),
        effect_frame,
        pd.DataFrame(means),
        _wide(effect_frame, "estimate_display"),
        _wide(effect_frame, "std_error_display"),
        diagnostic_frame,
        {
            "balancing": propensity_formula(
                treatment=config.treatment_variable, data=frame, covariates=config.covariates
            ),
            **{o: f"{o} ~ {config.treatment_variable}" for o in config.outcomes},
        },
        scores,
        pd.concat(method_scores, ignore_index=True),
        latex_tables(effect_frame, config),
        statistical_matching_console_table(
            effect_frame,
            covariance_type=config.covariance_type,
            outcomes=config.outcomes,
            aliases=config.outcome_aliases or {},
        ),
        config.covariance_type,
        config.outcome_types,
        config.outcome_aliases,
    )


class StatisticalMatchingSuite:
    """Compatibility suite facade for fitting a prepared frame."""

    def __init__(self, *, data: pd.DataFrame, config: StatisticalMatchingConfig) -> None:
        """Store source data and matching configuration.

        :param data: Observations to analyze.
        :param config: Matching settings.
        """
        self.data = data
        self.config = config

    def fit(self) -> StatisticalMatchingResult:
        """Fit all configured methods and outcomes.

        :return: Aggregated estimates and diagnostics.
        """
        return fit_suite(self.data, self.config)


StatisticalMatchingSuiteResult = StatisticalMatchingResult


def _wide(frame: pd.DataFrame, column: str) -> pd.DataFrame:
    """Pivot effects to one row per outcome.

    :param frame: Long-form outcome effects.
    :param column: Value field to pivot.
    :return: Wide table indexed by outcome.
    """
    return (
        frame.pivot(index="outcome", columns="method", values=column)
        .reset_index()
        .rename_axis(None, axis=1)
    )
