def add_inferred_openalex_field_columns(researchers: pd.DataFrame) -> pd.DataFrame:
    """Add OpenAlex Field IDs and labels inferred from researcher organizations.

    Matching rules use parsed organization units and, for explicitly
    institution-dependent evidence, the ``university_name`` value. Scopus ASJC
    columns are not consulted. Existing nonblank OpenAlex Field values are
    preserved.

    :param researchers: Researcher metadata rows.
    :return: A copy with inferred OpenAlex Field ID and label columns.
    """
    result = researchers.copy()
    if OPENALEX_FIELD_IDS_COLUMN not in result:
        result[OPENALEX_FIELD_IDS_COLUMN] = ""
    if OPENALEX_FIELD_LABELS_COLUMN not in result:
        result[OPENALEX_FIELD_LABELS_COLUMN] = ""

    for index, row in result.iterrows():
        if not _is_blank(row[OPENALEX_FIELD_IDS_COLUMN]):
            continue
        names = _organization_names(row.get(_ORGANIZATION_COLUMN))
        if not names:
            continue
        fields = _infer_fields(
            tuple(names),
            str(row.get(_UNIVERSITY_NAME_COLUMN, "")),
        )
        if not fields:
            continue

        result.at[index, OPENALEX_FIELD_IDS_COLUMN] = json.dumps(
            [field[0] for field in fields], ensure_ascii=False
        )
        if _is_blank(row[OPENALEX_FIELD_LABELS_COLUMN]):
            result.at[index, OPENALEX_FIELD_LABELS_COLUMN] = json.dumps(
                [field[1] for field in fields], ensure_ascii=False
            )
    return result


def _organization_names(value: object) -> list[str]:
    """Extract usable organization names from one source cell."""
    if _is_blank(value):
        return []
    if isinstance(value, str):
        return list(_parse_organization_names(value))
    return _filter_organization_names(organization_names(value))


@cache
def _parse_organization_names(value: str) -> tuple[str, ...]:
    """Parse and cache repeated serialized organization cells."""
    return tuple(_filter_organization_names(organization_names(value)))


def _filter_organization_names(names: list[str]) -> list[str]:
    """Remove placeholder values from parsed organization names."""
    return [
        name
        for name in names
        if normalize_organization_name(name) not in {"", "[]", "none", "null"}
    ]


@cache
def _infer_fields(names: tuple[str, ...], university_name: str = "") -> tuple[tuple[str, str], ...]:
    """Infer Fields per unit, ignoring administrative and expertise labels.

    :param names: Organization-unit names from one researcher record.
    :param university_name: Institution name used only for approved contextual
        rules.
    :return: Distinct Fields in stable URI order.
    """
    fields: set[tuple[str, str]] = set()
    for name in names:
        normalized_name = normalize_organization_name(name)
        if _is_administrative_name(normalized_name):
            continue
        unit_fields = {
            rule.field
            for rule in _FIELD_RULES
            if any(keyword_matches(keyword, normalized_name) for keyword in rule.keywords)
        }
        is_veterinary = any(term in normalized_name for term in _VETERINARY_TERMS)
        if is_veterinary:
            unit_fields.discard(("https://openalex.org/fields/27", "Medicine"))
            unit_fields.add(_VETERINARY_FIELD)
        fields.update(unit_fields)
    normalized_university = normalize_organization_name(university_name)
    normalized_names = tuple(normalize_organization_name(name) for name in names)
    if normalized_university == "uni ak wien" and any(
        name in {"mode", "cross disciplinary strategies"} for name in normalized_names
    ):
        fields.add(("https://openalex.org/fields/12", "Arts and Humanities"))
    if normalized_university == "kunstuni graz" and "institut 12 oberschutzen" in normalized_names:
        fields.add(("https://openalex.org/fields/12", "Arts and Humanities"))
    if (
        normalized_university == "fh oberosterreich"
        and "research center hagenberg" in normalized_names
        and any(name in _FH_OOE_HAGENBERG_COMPUTER_SCIENCE_UNITS for name in normalized_names)
    ):
        fields.add(("https://openalex.org/fields/17", "Computer Science"))
    if (
        normalized_university == "fh oberosterreich"
        and "research center hagenberg" in normalized_names
        and any(name in _FH_OOE_HAGENBERG_HEAL_UNITS for name in normalized_names)
    ):
        fields.update(
            {
                ("https://openalex.org/fields/17", "Computer Science"),
                ("https://openalex.org/fields/22", "Engineering"),
            }
        )
    if (
        normalized_university == "fh oberosterreich"
        and "research center steyr" in normalized_names
        and "focal area digital transformation" in normalized_names
    ):
        fields.update(
            {
                ("https://openalex.org/fields/14", "Business, Management and Accounting"),
                ("https://openalex.org/fields/17", "Computer Science"),
            }
        )
    if (
        normalized_university == "fh oberosterreich"
        and "research center wels" in normalized_names
        and "d farm" in normalized_names
    ):
        fields.update(
            {
                ("https://openalex.org/fields/11", "Agricultural and Biological Sciences"),
                ("https://openalex.org/fields/13", "Biochemistry, Genetics and Molecular Biology"),
            }
        )
    return tuple(sorted(fields, key=lambda field: field[0]))


def _is_administrative_name(normalized_name: str) -> bool:
    """Return whether a normalized unit is administrative or a generic label.

    :param normalized_name: Normalized organization-unit name.
    :return: Whether the unit should not contribute Field evidence.
    """
    if normalized_name.startswith("field of expertise"):
        return True
    if (
        "intensivpflege" in normalized_name
        or "interpersonelle kommunikation" in normalized_name
        or any(term in normalized_name for term in _DISCIPLINE_BEARING_PROGRAM_TERMS)
    ):
        return False
    if normalized_name in _ADMINISTRATIVE_EXACT_NAMES:
        return True
    return normalized_name.startswith(_ADMINISTRATIVE_PREFIXES) or any(
        marker in normalized_name for marker in _ADMINISTRATIVE_MARKERS
    )


def _is_blank(value: object) -> bool:
    """Return whether a metadata cell contains no meaningful value."""
    if value is None or value is pd.NA:
        return True
    if not isinstance(value, (list, dict, tuple, set)) and pd.isna(value):
        return True
    return str(value).strip().casefold() in {"", "nan", "none", "null", "[]", "<na>"}
